tup = (2, 4, 5, 7, 3)

print(tup)
print("Length:", len(tup))
print("Type:", type(tup))

# empty () is a tuple
num = ()
print(num)
print(type(num))

# When single element inside a () without , is a integer
numbers = (20)
print(numbers)
print(type(numbers))

# When sigle element inside a () with , is a tuple
numbers = (10,)
print(numbers)
print(type(numbers))
